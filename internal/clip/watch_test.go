// TestExcludedContent 验证空白内容过滤、图片上限边界与关闭限制后的记录行为
func TestExcludedContent(t *testing.T) {
	settings := types.DefaultSettings()
	for _, tc := range []struct {
		name string
		rec  types.Record
		want bool
	}{
		{"空格与制表符", types.Record{Kind: types.KindText, Text: " \t\u3000"}, true},
		{"空白行", types.Record{Kind: types.KindText, Text: "\r\n \n\t\r\n"}, true},
		{"空白富文本", types.Record{Kind: types.KindText, HTML: "<p>&nbsp;</p><br>"}, true},
		{"正常文本中的空白", types.Record{Kind: types.KindText, Text: "  第一行\n\n第二行  "}, false},
		{"正常富文本", types.Record{Kind: types.KindText, HTML: "<p>内容</p>"}, false},
		{"图片达到上限", types.Record{Kind: types.KindImage, Bytes: 5 << 20}, false},
		{"图片超过上限", types.Record{Kind: types.KindImage, Bytes: (5 << 20) + 1}, true},
		{"文件不受图片上限影响", types.Record{Kind: types.KindFile, Bytes: 10 << 20}, false},
	} {
		if got := excludedContent(&tc.rec, settings); got != tc.want {
			t.Errorf("%s：排除状态为 %v，期望 %v", tc.name, got, tc.want)
		}
	}
	settings.ExcludeWhitespace = false
	if excludedContent(&types.Record{Kind: types.KindText, Text: " \n\t"}, settings) {
		t.Fatal("关闭空白规则后仍排除空白文本")
	}
	settings.ImageLimitMiB = 2
	if !excludedContent(&types.Record{Kind: types.KindImage, Bytes: 3 << 20}, settings) {
		t.Fatal("修改图片上限后未应用新限制")
	}
	settings.ImageLimitMiB = 0
	if excludedContent(&types.Record{Kind: types.KindImage, Bytes: 10 << 20}, settings) {
		t.Fatal("图片大小设为 0 后仍按大小排除图片")
	}
}

// TestConfidentialContent 验证机密标记识别并保留普通内容与其他标记的记录行为
func TestConfidentialContent(t *testing.T) {
	for _, format := range []transfer.Format{"org.nspasteboard.ConcealedType", "ExcludeClipboardContentFromMonitorProcessing"} {
		if !confidentialContent([]transfer.Format{transfer.Text, format}) {
			t.Errorf("未识别机密内容标记 %s", format)
		}
	}
	for _, formats := range [][]transfer.Format{
		nil,
		{transfer.Text, transfer.HTML, transfer.PNG},
		{"org.nspasteboard.TransientType"},
		{"org.nspasteboard.AutoGeneratedType"},
	} {
		if confidentialContent(formats) {
			t.Errorf("非机密标记被识别为机密内容：%v", formats)
		}
	}
}

// TestExcludedApp 验证默认项与自定义项均仅按当前排除列表生效
func TestExcludedApp(t *testing.T) {
	for _, app := range types.DefaultExcludedApps() {
		if !excludedApp(app.ID, []types.ExcludedApp{app}) {
			t.Errorf("默认排除项 %s 未生效", app.Name)
		}
		if excludedApp(app.ID, nil) {
			t.Errorf("移除默认项后仍排除 %s", app.Name)
		}
	}
	apps := []types.ExcludedApp{{ID: "com.example.Private", Name: "自定义应用"}, {ID: "Private.exe", Name: "Windows 应用"}}
	for _, appID := range []string{"com.example.private", "PRIVATE.EXE"} {
		if !excludedApp(appID, apps) {
			t.Errorf("未排除自定义应用 %s", appID)
		}
		if excludedApp(appID, nil) {
			t.Errorf("移除规则后仍排除 %s", appID)
		}
	}
	for _, appID := range []string{"com.example.PrivateOther", "other-private.exe", "", "com.google.Chrome"} {
		if excludedApp(appID, apps) {
			t.Errorf("应用规则误排除 %q", appID)
		}
	}
}
